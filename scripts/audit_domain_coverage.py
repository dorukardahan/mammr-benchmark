#!/usr/bin/env python3
"""Summarize MAMMR category and domain coverage without printing pair text."""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATASET = ROOT / "data" / "mammr_pairs_public.json"

CATEGORY_GROUPS = {
    "memory_recall": {
        "short_query_long_memory",
        "conversational_recall",
        "context_implicit",
        "temporal",
    },
    "multilingual": {
        "turkish_morphology",
        "turkish_chars",
        "crosslingual",
        "code_switching",
        "code_mixed",
    },
    "semantic_matching": {
        "paraphrase",
        "partial_match",
        "specificity",
        "synonym_alias",
    },
    "technical_surface": {
        "code_to_description",
        "noise_typo",
    },
    "negative_controls": {
        "adversarial",
        "entity_confusion",
        "irrelevant",
        "negative_control",
        "same_topic_different_time",
        "similar_but_different",
    },
}

TECHNICAL_CUES = re.compile(
    r"\b(api|config|cron|database|docker|endpoint|error|gateway|http|json|log|model|provider|service|"
    r"sqlite|systemd|token|vector|yaml)\b|[/{}:=_`$]",
    re.IGNORECASE,
)

TURKISH_CUES = re.compile(r"[ığüşöçİĞÜŞÖÇ]|\b(ne|neden|hangi|nasıl|şu|bunu|bana|hafıza)\b", re.IGNORECASE)


def load_rows(path: Path) -> list[dict[str, Any]]:
    rows = json.loads(path.read_text())
    if not isinstance(rows, list):
        raise ValueError("dataset root must be a list")
    return rows


def category_group(category: str) -> str:
    for group, categories in CATEGORY_GROUPS.items():
        if category in categories:
            return group
    return "unmapped"


def build_report(rows: list[dict[str, Any]]) -> dict[str, Any]:
    category_counts: Counter[str] = Counter()
    group_counts: Counter[str] = Counter()
    group_label_counts: dict[str, Counter[str]] = defaultdict(Counter)
    technical_hits = 0
    turkish_hits = 0

    for row in rows:
        category = str(row["category"])
        expected = str(row["expected"])
        text = f"{row['query']}\n{row['document']}"
        group = category_group(category)
        category_counts[category] += 1
        group_counts[group] += 1
        group_label_counts[group][expected] += 1
        if TECHNICAL_CUES.search(text):
            technical_hits += 1
        if TURKISH_CUES.search(text):
            turkish_hits += 1

    return {
        "pair_count": len(rows),
        "category_counts": dict(sorted(category_counts.items())),
        "group_counts": dict(sorted(group_counts.items())),
        "group_label_counts": {
            group: dict(sorted(counter.items())) for group, counter in sorted(group_label_counts.items())
        },
        "technical_cue_pairs": technical_hits,
        "turkish_cue_pairs": turkish_hits,
        "unmapped_categories": sorted(
            category for category in category_counts if category_group(category) == "unmapped"
        ),
    }


def render_markdown(report: dict[str, Any]) -> str:
    lines = [
        "# Domain Coverage Report",
        "",
        "Generated by `scripts/audit_domain_coverage.py`.",
        "",
        "This report is intentionally aggregate-only. It does not print query or document text.",
        "",
        "## Summary",
        "",
        f"- pairs: `{report['pair_count']}`",
        f"- technical cue pairs: `{report['technical_cue_pairs']}`",
        f"- Turkish cue pairs: `{report['turkish_cue_pairs']}`",
        f"- unmapped categories: `{len(report['unmapped_categories'])}`",
        "",
        "The cue counts are heuristic text cues, not manual domain labels.",
        "`technical cue pairs` means a query or document matched common command, config, service, API, log, or structured-text markers.",
        "`Turkish cue pairs` means a query or document matched Turkish characters or common Turkish recall words.",
        "",
        "## Category Groups",
        "",
        "| Group | Pairs | high | medium_high | medium | low |",
        "|-------|-------|------|-------------|--------|-----|",
    ]
    for group, count in report["group_counts"].items():
        labels = report["group_label_counts"].get(group, {})
        lines.append(
            f"| {group} | {count} | {labels.get('high', 0)} | "
            f"{labels.get('medium_high', 0)} | {labels.get('medium', 0)} | {labels.get('low', 0)} |"
        )

    lines.extend([
        "",
        "## Category Counts",
        "",
        "| Category | Group | Pairs |",
        "|----------|-------|-------|",
    ])
    for category, count in report["category_counts"].items():
        lines.append(f"| {category} | {category_group(category)} | {count} |")

    lines.extend([
        "",
        "## Interpretation",
        "",
        "MAMMR is intentionally strongest for multilingual agent memory, technical operations, and near-miss control cases.",
        "The current public v0.1 candidate should not be framed as a broad-domain benchmark.",
        "",
        "The next domain-breadth step is not to dilute the current release. It is to add a separate v0.2 extension set with public-safe examples from non-DevOps domains such as personal productivity, education, writing workflows, finance-like record keeping without real financial data, and general assistant memory.",
        "",
        "## v0.2 Extension Plan",
        "",
        "| Extension area | Suggested public-safe examples | Goal |",
        "|----------------|--------------------------------|------|",
        "| personal productivity | meeting notes, task preferences, calendar-like reminders with fake names | Test everyday assistant recall without private life details. |",
        "| education | course notes, homework preferences, concept explanations | Test learning-memory retrieval. |",
        "| writing workflows | draft constraints, style preferences, editorial decisions | Test creative and document-memory recall. |",
        "| finance-like records | fake invoices, budget categories, subscription reminders | Test structured personal-record recall without real financial data. |",
        "| general assistant memory | preferences, recurring instructions, stale-vs-current facts | Test non-technical long-running assistant memory. |",
        "",
        "This should be a separate v0.2 extension set so the v0.1 technical-agent claims remain stable.",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    report = build_report(load_rows(args.dataset))
    if report["unmapped_categories"]:
        print(f"unmapped_categories={report['unmapped_categories']}")
        return 1
    if args.json:
        print(json.dumps(report, indent=2, ensure_ascii=False))
    else:
        print(render_markdown(report))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
